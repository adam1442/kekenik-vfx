#!/usr/bin/env node
/**
 * Regenerates THIRD_PARTY_NOTICES.md from package.json + node_modules.
 *
 * Lists every runtime dependency (package.json "dependencies" and, recursively, their own dependencies) with its version, license
 * and copyright line, and embeds the full license text found in the installed package. Run `npm ci` first, then `npm run notices`.
 * Pass `--check` to fail (exit code 1) when the committed file is out of date.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(import.meta.url), '..', '..');
const nm = join(root, 'node_modules');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const seen = new Map();
function visit(name, from) {
  if (seen.has(name)) return;
  const dirs = [join(from, 'node_modules', name), join(nm, name)];
  const dir = dirs.find((d) => existsSync(join(d, 'package.json')));
  if (!dir) throw new Error(`Package "${name}" is not installed. Run "npm ci" first.`);
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const licenseFile = readdirSync(dir).find((f) => /^(licen[sc]e|copying|notice)(\.|$)/i.test(f));
  const text = licenseFile ? readFileSync(join(dir, licenseFile), 'utf8').trim() : '';
  const copyright =
    text
      .split('\n')
      .map((l) => l.trim())
      .filter((l) => /^copyright\b|^\(c\)|^©/i.test(l))
      .join('; ') || (typeof meta.author === 'string' ? meta.author : meta.author?.name ?? 'see package');
  const license = typeof meta.license === 'string' ? meta.license : meta.license?.type ?? 'UNKNOWN';
  seen.set(name, { name, version: meta.version, license, copyright, homepage: meta.homepage ?? meta.repository?.url ?? '', text });
  for (const dep of Object.keys(meta.dependencies ?? {})) visit(dep, dir);
}
for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, root);

const list = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const out = [
  '# Third-party notices',
  '',
  `Kekenik VFX is released under the MIT License (see [LICENSE](LICENSE)). It bundles the open-source packages listed below.`,
  'Development-only tools (Vite, Vitest, TypeScript, ESLint, Prettier and their dependencies) are not shipped in the built site.',
  '',
  'This file is generated by `npm run notices` (`tools/generate-notices.mjs`). Do not edit it by hand.',
  '',
  '| Package | Version | License | Copyright |',
  '|---|---|---|---|',
  ...list.map((d) => `| ${d.name} | ${d.version} | ${d.license} | ${d.copyright.replace(/\|/g, '/')} |`),
  '',
  '## Assets and data',
  '',
  '- Fonts: none are bundled. The interface uses the system font stack (see `public/fonts/README.md`).',
  '- Icons: the favicon and all interface icons are original vector artwork drawn for this project.',
  '- Textures, noise, environment lighting and sample data are generated procedurally by the application or authored in this repository.',
  '',
  '## License texts',
  '',
];
for (const d of list) {
  out.push(`### ${d.name} ${d.version} (${d.license})`, '');
  if (d.homepage) out.push(`Source: ${d.homepage}`, '');
  out.push('```text', d.text || `License: ${d.license}`, '```', '');
}
const body = out.join('\n');
const target = join(root, 'THIRD_PARTY_NOTICES.md');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== body) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run: npm run notices');
    process.exit(1);
  }
} else {
  writeFileSync(target, body);
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${list.length} packages)`);
}
